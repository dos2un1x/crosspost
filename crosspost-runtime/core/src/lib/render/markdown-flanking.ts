/**
 * 消除 markdown 强调（`**`）的 flanking 失效问题。
 *
 * CommonMark 规定：`**` 若紧跟一个 Unicode 标点（全角/直角引号、冒号、逗号、括号、书名号等），
 * 且其前一个字符不是空白也不是标点，则该 `**` 不满足 "left-flanking"，不会被当作强调开篇 ——
 * 导致 `**"训练数据从哪来"…**` 这类写法加粗失效、`**` 原样输出。
 * 该规则在 markdown-it 与 marked 中均一致（不同于"只跟引号有关"，而是所有标点都触发）。
 *
 * 修法：对这类 `**` 之后插入一个零宽空格（U+200B，渲染时不可见）：
 *   把 `**` 后的字符从"标点"变为"非标点"（U+200B 非标点、非空白），使其满足 left-flanking，
 *   从而正确开启强强调；内容与外观均不受影响。
 */
export function normalizeBoldFlanking(md: string): string {
  if (!md) return md
  // `**` 前一个字符非空白/非标点（否则已经能开强调），且后一个字符是标点，则插入 U+200B。
  // `(?!\*)` 避免误命中 `***`（粗斜体，语义不同）。
  return md.replace(/(?<![\s\p{P}])\*\*(?!\*)(?=\p{P})/gu, '**\u200b')
}
